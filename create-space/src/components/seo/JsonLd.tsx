type Props = {
  data: Record<string, unknown> | Record<string, unknown>[];
};

export const JsonLd = ({ data }: Props) => {
  const items = Array.isArray(data) ? data : [data];
  return (
    <>
      {items.map((schema, i) => (
        <script
          key={i}
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(schema) }}
        />
      ))}
    </>
  );
};
