const DEFAULT_INDUSTRIES = [
  "Automotive", "Manufacturing", "Retail", "Healthcare",
  "Education", "Logistics", "Financial Services", "MSMEs",
];

function makeProductGeo(
  slug: string,
  name: string,
  tagline: string,
  whatIsIt: string,
  whyRequired: string,
  benefits: string[],
  useCases: string[],
  faqs: GeoPageContent["faqs"],
  pricingModel: string,
  successStory: GeoPageContent["successStory"],
): GeoPageContent {
  const seo = PRODUCT_SEO[slug];
  return {
    slug,
    type: "product",
    title: name,
    metaTitle: `${name} | ${tagline} — Zentroverse Global`,
    metaDescription: `${seo?.description ?? tagline}. ${BRAND_TAGLINE} for enterprises, dealerships and MSMEs across India.`,
    h1: `${name} — ${tagline}`,
    tagline,
    whatIsIt,
    whyRequired,
    benefits,
    keyFeatures: benefits.slice(0, 4),
    problemsSolved: [whyRequired.split(".")[0] + ".", "Manual processes causing delays and errors.", "Lack of integrated data and reporting.", "Difficulty scaling without automation."],
    howItWorks: ["Discovery & requirement mapping", "Solution design & configuration", "Implementation & integration", "Training & go-live", "Support & continuous optimization"],
    industries: DEFAULT_INDUSTRIES,
    useCases,
    faqs,
    pricingModel,
    successStory,
    keywords: seo?.keywords ?? [],
    relatedLinks: TOPIC_CLUSTERS.map((c) => ({
      label: c.heading,
      href: `/services/${c.id}`,
    })),
  };
}

